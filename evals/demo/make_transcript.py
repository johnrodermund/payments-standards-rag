"""Render a readable transcript (evals/demo/DEMO.md) from the recorded run (deployed_run.json).

    python evals/demo/make_transcript.py

Shows a fixed selection (the first answerable question of each category, three escalations, and every
answerable question that escalated) so the page is not hand-picked for flattering results.
"""

import json
from pathlib import Path

HERE = Path(__file__).parent


def fence(text: str) -> str:
    return "> " + text.strip().replace("\n", "\n> ")


def main() -> None:
    data = json.loads((HERE / "deployed_run.json").read_text(encoding="utf-8"))
    results, summary = data["results"], data["summary"]
    seen, picked = set(), []
    for r in results:
        if r["set"] == "golden" and r["answerable"] and r["category"] not in seen and r["status"] == 200 and not r.get("escalated"):
            seen.add(r["category"])
            picked.append(r)
    failed = [r for r in results if r["set"] == "golden" and r["answerable"] and r.get("escalated")]
    refused = [r for r in results if not (r["set"] == "golden" and r["answerable"]) and r["status"] == 200 and r.get("escalated")][:3]
    errors = [r for r in results if r["status"] != 200]

    out = [
        "# Recorded demo: the assistant running on AWS",
        "",
        "This is a transcript of a recorded run, **not a live service**. The stack was deployed to AWS (ECS Fargate, ALB,",
        "RDS PostgreSQL with pgvector) on 2026-11-21 in replay mode, queried with the golden set and the off-topic set,",
        "and destroyed. Raw responses: [`deployed_run.json`](deployed_run.json). Generated by `make_transcript.py`.",
        "",
        (
            f"Totals: {summary['answered']} of {summary['answerable_questions']} answerable questions answered "
        f"({summary['answerable_escalated']} escalated), retrieval hit@5 {summary['hit_at_5']}/{summary['answerable_questions']}; "
        f"{summary['escalated_correctly']} of {summary['should_escalate']} questions that should escalate did; "
        f"{summary['http_errors_total']} request returned 503 (no recording in replay mode)."
        ),
        "",
        "## Answered, with sources (first question of each category)",
    ]
    for r in picked:
        out += ["", f"**{r['question']}** (`{r['category']}`)", "", fence(r["answer"]), ""]
        out += [f"Sources: {', '.join('`' + s['id'].split('#')[-1] + '`' for s in r['sources'])} (top score {r['sources'][0]['score']:.2f})"]
    out += ["", "## Escalated to a human instead of guessing (examples)"]
    for r in refused:
        out += ["", f"**{r['question']}**", f"- escalated, reason `{r['reason']}`"]
    out += ["", "## Answerable questions the assistant did not answer (all of them)"]
    for r in failed:
        out += ["", f"**{r['question']}**", f"- escalated, reason `{r['reason']}`; retrieval hit@5: {r['hit_at_5']}"]
    out += ["", "## Request that failed"]
    for r in errors:
        out += ["", f"**{r['question']}**", f"- HTTP {r['status']}: replay mode had no recorded answer"]
    (HERE / "DEMO.md").write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
